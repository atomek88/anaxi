// Snapshot the example project for the exploration: the checker's JSON plus every doc's raw markdown → data.js
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const ex = path.resolve(import.meta.dirname, '../../example');
const model = JSON.parse(execFileSync('node', [path.resolve(ex, '../tools/anaxi-check.mjs'), 'status', '--json', '--dir', ex], { encoding: 'utf8' }));
const files = {};
const walk = (d) => { for (const e of fs.readdirSync(path.join(ex, d), { withFileTypes: true })) {
  const r = d ? `${d}/${e.name}` : e.name;
  if (e.isDirectory()) walk(r); else if (r.endsWith('.md') && !['README.md', 'INDEX.md'].includes(r)) files[r] = fs.readFileSync(path.join(ex, r), 'utf8');
} };
walk('');
fs.writeFileSync(path.join(import.meta.dirname, 'data.js'), `// generated by data.mjs from ../../example — don't edit\nwindow.ANAXI = ${JSON.stringify({ model, files })};\n`);
console.log(`data.js: ${model.items.length} items, ${model.inactive.length} inactive, ${Object.keys(files).length} files`);
